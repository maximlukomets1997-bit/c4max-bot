# ───────────────────────────────────────────────
#  database/_core.py — ФУНДАМЕНТ работы с базой (02.09.2026).
#
#  Выделен из history.py, который вырос до 2804 строк и 122 функций. Резать
#  его оказалось безопасно: двенадцать тем внутри него разговаривают между
#  собой ВСЕГО ТРИ РАЗА, а остальные 103 связи ведут сюда — к замку и
#  соединению. То есть это был не «один механизм», а дюжина независимых,
#  сложенных в один файл поверх общего фундамента. Тем же разрезом и по той
#  же причине когда-то разошлись admin.py (2140 строк) и jobs.py (837).
#
#  Здесь лежит ровно то, чем пользуются ВСЕ остальные файлы пакета:
#    _lock            — замок всех операций с базой (+ откат при ошибке)
#    _get_connection  — общее соединение на весь процесс
#    close_db         — закрытие при остановке бота
#    backup_to        — снимок базы средствами самой SQLite
#
#  ⚠️ СОЕДИНЕНИЕ БРАТЬ ТОЛЬКО ЧЕРЕЗ _get_connection(), НИКОГДА НЕ ИМПОРТИРОВАТЬ
#  переменную _conn. Она переприсваивается (открытие, закрытие), и модуль,
#  забравший её к себе в шапку, навсегда останется со снимком None: бот
#  запустится, а первое же обращение к базе упадёт. Ровно на этом такие
#  переезды обычно и ломаются. Поэтому _conn не входит в то, что этот файл
#  отдаёт наружу, и за его пределами не встречается ни разу — проверено.
#
#  ⚠️ ИМЯ ЛОГГЕРА ЗДЕСЬ ВАЖНО. Каждый SQL-запрос пишется на уровне DEBUG
#  (_LoggingConnection ниже), и чтобы он не заливал лог, logging_setup.py
#  глушит его по имени. Глушилка стоит на «database» — то есть на весь
#  пакет; до 02.09.2026 она стояла на «database.history», и переезд этого
#  файла молча выпустил бы SQL-отладку в консоль и в файл.
# ───────────────────────────────────────────────

import os
import time
import sqlite3
import threading
import logging

# ⚠️ config ИМПОРТИРУЕТСЯ ЦЕЛИКОМ, а путь к базе берётся из него В МОМЕНТ
# ОТКРЫТИЯ соединения (см. _get_connection). Строка `from config import DB_PATH`
# была бы СНИМКОМ: обе проверки — preflight и selftest — уводят базу во
# временную папку, чтобы не трогать боевую, и со снимком они молча писали бы
# в НАСТОЯЩУЮ history.db. Поймано этой же предполётной проверкой 02.09.2026
# при выносе фундамента из history.py.
#
# Это то же самое правило, что и у _conn ниже: переменную, которую кто-то
# меняет, нельзя забирать к себе в шапку — читать только в момент обращения.
import config

logger = logging.getLogger(__name__)

# ───────────────────────────────────────────────
#  Замок базы (2026-07-27)
#
#  Один глобальный замок — защищает все операции с БД от гонки данных.
#  Раньше это был обычный threading.Lock; теперь — обёртка вокруг него,
#  которая ДОПОЛНИТЕЛЬНО откатывает незавершённую транзакцию, если функция
#  выпала с ошибкой на середине записи. Раньше это было не нужно: каждая
#  функция открывала СВОЁ соединение и бросала его при ошибке (транзакция
#  умирала вместе с соединением). Теперь соединение одно на весь процесс —
#  недописанная транзакция висела бы в нём и её содержимое уехало бы в чужой
#  commit следующей функции. Отсюда откат.
#
#  ⚠️ Замок НЕ реентерабельный — как и прежний threading.Lock. Значит,
#  get_setting/set_setting (они берут замок сами) звать только ВНЕ блока
#  `with _lock`, иначе бот повиснет намертво. Правило старое, не изменилось.
# ─────────────────────────────────────────────

class _DbLock:
    """Замок всех операций с БД + откат недописанной транзакции при ошибке."""

    def __init__(self):
        self._lock = threading.Lock()

    def __enter__(self):
        self._lock.acquire()
        return self

    def __exit__(self, exc_type, exc, tb):
        if exc_type is not None:
            try:
                if _conn is not None and _conn.in_transaction:
                    _conn.rollback()
                    logger.debug("Откат незавершённой транзакции после ошибки: %s", exc)
            except Exception:
                pass  # откат — страховка, своих ошибок она порождать не должна
        self._lock.release()
        return False  # исключение наружу, как и раньше


_lock = _DbLock()


