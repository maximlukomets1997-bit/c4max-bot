#!/bin/bash
# ─────────────────────────────────────────────────────────────
#  deploy.sh — обновление бота на сервере (2026-07-27)
# ─────────────────────────────────────────────────────────────
# ЕДИНСТВЕННОЕ место, где записано, как бот обновляется. Зовут его двое:
#   1) «Отправить изменения на GitHub.bat» с компьютера Максима (через ssh);
#   2) кнопка «🔄 ПЕРЕЗАПУСТИТЬ БОТА» в админ-панели (services/deploy.py).
# Две отдельные реализации одного и того же неизбежно разъезжаются — поэтому
# логика здесь одна на всех.
#
# ⚠️ ЭТОТ СЦЕНАРИЙ НЕ ПЕРЕЗАПУСКАЕТ БОТА. Он только приводит код в порядок и
# докладывает, что вышло. Перезапускает тот, кто позвал:
#   .bat  → systemctl restart c4max-bot (он работает под root);
#   бот   → своим штатным механизмом (завершается, systemd поднимает) —
#           так отрабатывают его хуки остановки, и лишних прав ему не нужно.
#
# ⚠️ ЗАПУСКАТЬ ТОЛЬКО ИЗ КОПИИ (см. services/deploy.py и .bat): обновление
# заменяет и сам этот файл, а bash дочитывает сценарий с диска по ходу
# выполнения — подмена на лету оборвала бы его на середине.
#
# ⚠️ Работать только от имени c4bot: папка бота принадлежит ему, и git,
# запущенный от root, наплодил бы там root-овых файлов.
#
# Печатает строки вида КЛЮЧ=значение — их разбирает services/deploy.py:
#   STATUS   = UPDATED | NOCHANGE | ROLLBACK | NETFAIL | FAIL | BUSY
#   VERSION  = версия, на которой бот остался
#   WAS      = версия до обновления (только у UPDATED)
#   MSG      = человеческая строка для показа Максиму
#   ERR      = текст ошибки (только у ROLLBACK/FAIL)

BOT=/home/c4bot/bot
PY="$BOT/.venv/bin/python"
PIP="$BOT/.venv/bin/pip"

# Замок: два обновления разом (нажал кнопку и одновременно запустил .bat)
# подрались бы за один и тот же git.
# ⚠️ Замок ЛЕЖИТ НЕ В /tmp. В Ubuntu включена защита fs.protected_regular:
# в общей папке с «липким» битом (/tmp) нельзя открыть на запись чужой файл —
# даже root не может переписать файл, созданный c4bot. А сценарий зовут двое,
# и они молча получали бы «обновление уже идёт» вместо работы (поймано
# тестом 2026-07-27). В домашней папке c4bot такой ловушки нет.
exec 9>/home/c4bot/.c4max-deploy.lock
if ! flock -n 9; then
    echo "STATUS=BUSY"
    echo "MSG=Обновление уже идёт, подожди несколько секунд."
    exit 0
fi

cd "$BOT" 2>/dev/null || {
    echo "STATUS=FAIL"
    echo "MSG=Папка бота не найдена: $BOT"
    exit 0
}

WAS_COMMIT=$(git rev-parse HEAD 2>/dev/null)
WAS_VER=$(cat VERSION 2>/dev/null || echo "?")

# ── 1. Смотрим, есть ли новое ────────────────────────────────
if ! git fetch -q --tags origin main 2>/dev/null; then
    echo "STATUS=NETFAIL"
    echo "VERSION=$WAS_VER"
    echo "MSG=Не удалось связаться с GitHub. Бот остался на v$WAS_VER."
    exit 0
fi

NEW_COMMIT=$(git rev-parse origin/main 2>/dev/null)

if [ "$WAS_COMMIT" = "$NEW_COMMIT" ]; then
    echo "STATUS=NOCHANGE"
    echo "VERSION=$WAS_VER"
    echo "MSG=Нового кода нет, бот уже на v$WAS_VER."
    exit 0
fi

# ── 2. Забираем ──────────────────────────────────────────────
# Только «перемоткой вперёд»: если на сервере кто-то правил файлы руками,
# честнее отказаться, чем молча слепить чужие правки с новыми.
if ! git merge --ff-only -q origin/main 2>/dev/null; then
    echo "STATUS=FAIL"
    echo "VERSION=$WAS_VER"
    echo "MSG=Не удалось наложить обновление (на сервере есть свои правки). Бот остался на v$WAS_VER."
    exit 0
fi

NEW_VER=$(cat VERSION 2>/dev/null || echo "?")

# ── 3. Библиотеки, если список изменился ─────────────────────
if git diff --name-only "$WAS_COMMIT" "$NEW_COMMIT" 2>/dev/null | grep -qx "requirements.txt"; then
    if ! "$PIP" install -q -r "$BOT/requirements.txt" 2>/dev/null; then
        git reset --hard -q "$WAS_COMMIT"
        echo "STATUS=ROLLBACK"
        echo "VERSION=$WAS_VER"
        echo "MSG=Не удалось поставить новые библиотеки. Вернулся на v$WAS_VER."
        exit 0
    fi
fi

# ── 4. Проверяем, что новый код запускается ──────────────────
# Сначала синтаксис всех файлов проекта (папку .venv не трогаем — там чужие
# библиотеки, и часть из них намеренно не компилируется под нашу версию).
# ⚠️ КЛЮЧ -f (принудительно) ОБЯЗАТЕЛЕН, и вот почему. Python хранит рядом с
# каждым файлом заранее переведённую копию и считает её годной, если у
# исходника совпали ДВА признака: размер и время изменения с точностью до
# секунды. На тесте 2026-07-27 два разных config.py совпали по обоим —
# оказались ровно по 21 байту и записаны в одну секунду. Проверка загрузила
# СТАРУЮ исправную копию, отчиталась «всё хорошо», и сломанный код остался на
# сервере. С -f перевод делается заново всегда, и такой обман невозможен.
PROBLEM=""
ERRTEXT=$("$PY" -m compileall -q -f -x '(\.venv|__pycache__)' "$BOT" 2>&1) || PROBLEM="синтаксис"

# Затем настоящая загрузка ключевых модулей: ловит то, чего не видит
# компиляция — опечатку в имени, пропавшую библиотеку, ошибку в config.
if [ -z "$PROBLEM" ]; then
    ERRTEXT=$("$PY" -c "import config, database.history, services.gemini, handlers" 2>&1) || PROBLEM="загрузка"
fi

if [ -n "$PROBLEM" ]; then
    git reset --hard -q "$WAS_COMMIT"
    echo "STATUS=ROLLBACK"
    echo "VERSION=$WAS_VER"
    echo "MSG=Новый код v$NEW_VER не запускается ($PROBLEM). Вернулся на v$WAS_VER."
    echo "ERR=$(echo "$ERRTEXT" | tail -3 | tr '\n' ' ')"
    exit 0
fi

# ── 5. Готово ────────────────────────────────────────────────
echo "STATUS=UPDATED"
echo "WAS=$WAS_VER"
echo "VERSION=$NEW_VER"
echo "MSG=Забрал v$NEW_VER (было v$WAS_VER), проверка пройдена."
exit 0
