# ───────────────────────────────────────────────
#  http.py — переиспользуемые соединения для запросов к нейросетям и сайтам
#            (2026-07-27, ускорение)
#
#  ЗАЧЕМ. Раньше каждый запрос звался как requests.post(...) — а это каждый раз
#  НОВОЕ соединение: поиск адреса, TCP, защищённое «рукопожатие» TLS. Замерено
#  до Google (generativelanguage.googleapis.com): 130–200 мс НА КАЖДЫЙ запрос.
#  А запросов на один ответ бота обычно два — сначала эмбеддинг для поиска по
#  базе знаний, потом сама модель. То есть ~0.3 секунды каждого ответа уходило
#  на «здравствуйте», ещё до того как модель начала думать. Сработала цепочка
#  подстраховки — больше.
#
#  Теперь соединения держатся открытыми и переиспользуются: рукопожатие платится
#  один раз на хост, дальше запросы идут по готовому каналу.
#
#  ПОЧЕМУ ПО СЕССИИ НА ПОТОК, а не одна общая. Запросы к моделям идут из рабочих
#  потоков (run_in_executor), а requests.Session по документации не обещает
#  потокобезопасности. Своя сессия у каждого потока снимает вопрос полностью и
#  ничего не стоит: потоки в пуле переиспользуются, поэтому рукопожатие в каждом
#  случается один раз за жизнь бота.
#
#  ⚠️ ПОВТОРЫ ВЫКЛЮЧЕНЫ НАМЕРЕННО (max_retries=0). У бота своя логика повторов
#  и подстраховки в services/gemini.py (2 попытки активной модели, уход по
#  цепочке, а на таймаут — сразу к следующей модели без второй попытки).
#  Включишь повторы здесь — они умножатся на те, и таймаут в 60 секунд
#  превратится в несколько минут молчания. Не включать.
# ─────────────────────────────────────────────

import logging
import threading

import requests
from requests.adapters import HTTPAdapter

logger = logging.getLogger(__name__)

_local = threading.local()


def session() -> requests.Session:
    """
    Сессия текущего потока (создаётся при первом обращении).
    Пользоваться как обычным requests: session().post(...), session().get(...).
    Исключения те же самые (requests.exceptions.*) — обработка ошибок
    в вызывающем коде не меняется.
    """
    s = getattr(_local, "session", None)
    if s is None:
        s = requests.Session()
        # pool_maxsize с запасом: бот ходит к нескольким хостам (Google,
        # Alibaba, DeepSeek, Xiaomi, api.telegram.org, wtmobile.com).
        adapter = HTTPAdapter(pool_connections=8, pool_maxsize=8, max_retries=0)
        s.mount("https://", adapter)
        s.mount("http://", adapter)
        _local.session = s
        logger.debug("Создана сессия соединений для потока %s", threading.current_thread().name)
    return s
