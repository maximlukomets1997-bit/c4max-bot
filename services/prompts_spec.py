BY_KEY = {item["key"]: item for item in PROMPTS}


def read(key: str) -> str:
    """
    Текст промпта КАК ОН ХРАНИТСЯ. Именно его показываем в поле для правки:
    читалки бота местами подставляют запасное значение из config, и правь мы
    показанное ими — в базу уехала бы копия запасного текста.
    """
    return get_setting(key, "")


def write(key: str, text: str) -> int:
    """
    Сохраняет промпт. Возвращает длину сохранённого текста.

    ⚠️ Текст НЕ чистится и не подрезается — ровно как у команды /prompt_set.
    Промпт это инструкция модели: любая «нормализация» здесь молча меняла бы
    то, что человек написал. Единственное — убираем пробелы по краям, как
    делает чтение из .txt-файла в боте.
    """
    if key not in BY_KEY:
        raise KeyError(key)
    text = (text or "").strip()
    set_setting(key, text)
    return len(text)


def assembled_system_prompt() -> tuple:
    """
    Что на самом деле уйдёт модели как системный промпт: основной текст плюс
    дополнения. Ровно та же сборка, что у бота
    (database/history.py::get_active_system_prompt) — не своя копия.

    Возвращает (текст, длина).
    """
    from database.history import get_active_system_prompt
    prompt, _is_custom, _additions = get_active_system_prompt()
    return prompt, len(prompt)
