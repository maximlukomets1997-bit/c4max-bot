#!/bin/bash
# ─────────────────────────────────────────────────────────────
#  deploy-restart.sh — обновить и перезапустить (для вызова с ПК)
# ─────────────────────────────────────────────────────────────
# Тонкая обёртка вокруг deploy.sh: зовёт общий сценарий обновления и, если он
# что-то забрал, перезапускает службу. Ею пользуется «Отправить изменения на
# GitHub.bat» с компьютера Максима — одной строкой `ssh c4max c4max-update`.
#
# ⚠️ РАБОЧАЯ КОПИЯ ЛЕЖИТ НЕ ЗДЕСЬ, А В /usr/local/bin/c4max-update.
# Причина: этот файл лежит в репозитории, а обновление его же и заменяет —
# bash дочитывает сценарий с диска по ходу выполнения, и подмена оборвала бы
# его на середине. Здесь хранится ИСХОДНИК, чтобы правки были видны в истории;
# поправил — переустанови на сервере:
#     scp deploy-restart.sh root@сервер:/usr/local/bin/c4max-update
#     ssh root@сервер chmod 755 /usr/local/bin/c4max-update
#
# Запускается от root (перезапуск службы), а сам deploy.sh — от c4bot,
# которому принадлежит папка бота.

# Куда класть копию сценария. Требований ДВА, и они тянут в разные стороны:
#   • НЕ в /tmp — там защита Ubuntu (fs.protected_regular) не даёт одному
#     пользователю переписать файл другого, а этот же сценарий копирует себе
#     и бот (от c4bot); общий путь в /tmp они бы отбирали друг у друга;
#   • НЕ в /root — туда закрыт вход всем, кроме root, а СЦЕНАРИЙ ЗАПУСКАЕТСЯ
#     ОТ c4bot. Наступили на это 2026-07-27: обёртка молча получала
#     «Permission denied», ответ приходил пустой, и она сообщала «перезапуск
#     не требуется» — выглядело так, будто обновление прошло и ничего нового
#     не было. Файл при этом не подхватывался вообще.
# Итог: домашняя папка бота, файл с общим правом на чтение.
BRAIN=/home/c4bot/.c4max-deploy-from-pc.sh
BOT=/home/c4bot/bot

# Сценарий обновления берём ИЗ СВЕЖЕГО КОДА НА GITHUB, а не из папки бота.
# Это решает сразу две беды:
#   1) первый запуск — deploy.sh приезжает тем же обновлением, которое он же и
#      выполняет, то есть в папке бота его ещё нет;
#   2) подмена на ходу — обновление заменяет этот файл, а bash дочитывает
#      сценарий с диска по мере выполнения и оборвался бы на середине.
# Запасной путь — копия из папки бота (вдруг GitHub недоступен).
sudo -u c4bot git -C "$BOT" fetch -q --tags origin main 2>/dev/null
sudo -u c4bot git -C "$BOT" show origin/main:deploy.sh > "$BRAIN" 2>/dev/null \
    || cp "$BOT/deploy.sh" "$BRAIN" 2>/dev/null \
    || {
        echo "  Сервер: не нашёл сценарий обновления ни на GitHub, ни у себя."
        exit 1
    }
# Пустой файл вместо сценария (git отдал пустоту) — тоже отказ.
if [ ! -s "$BRAIN" ]; then
    echo "  Сервер: сценарий обновления пуст, обновление отменено."
    exit 1
fi
# Файл создан от root, а запускать его будет c4bot — нужно право на чтение.
chmod 644 "$BRAIN"

# ⚠️ Пустой ответ сценария означает, что он не запустился (права, синтаксис).
# Молчать об этом нельзя: раньше обёртка в таком случае бодро сообщала
# «перезапуск не требуется», и выглядело это как успешное обновление.
check_output() {
    if [ -z "$1" ]; then
        echo "  Сервер: сценарий обновления не запустился — обновления НЕ БЫЛО."
        exit 1
    fi
}

OUT=$(sudo -u c4bot bash "$BRAIN" 2>&1)
check_output "$OUT"

# Человеческую строку показываем всегда — ради неё всё и затевалось.
echo "$OUT" | sed -n 's/^MSG=/  Сервер: /p'
echo "$OUT" | sed -n 's/^ERR=/  Ошибка: /p'

if echo "$OUT" | grep -q '^STATUS=UPDATED'; then
    if systemctl restart c4max-bot; then
        echo "  Сервер: бот перезапущен на новой версии."
    else
        echo "  Сервер: НЕ УДАЛОСЬ перезапустить бота, смотри логи."
        exit 1
    fi
else
    # Нечего было забирать или откатились — перезапуск ничего не изменит,
    # а бот на 10 секунд замолчал бы зря.
    echo "  Сервер: перезапуск не требуется."
fi
