import asyncio
import json
import logging
import time

logger = logging.getLogger(__name__)

# Когда поднялся ЭТОТ процесс. Модуль загружается при старте бота (main.py
# тянет jobs в шапке), так что это и есть время запуска с точностью до секунд.
#
# ⚠️ Нужно ровно для одного случая: в следе уведомления НЕТ времени отправки.
# Так выглядят следы, оставленные кодом до 03.09.2026, — и первый же переход
# со старой версии на новую даёт именно такой след. Считать его «неизвестно
# каким старым» и не трогать нельзя: сообщение зависало бы навсегда, то есть
# ровно так, как было до всей этой правки (поймано на живом боте в тот же
# день). Подробности — в notice_since ниже.
_STARTED_AT = time.time()


# ───────────────────────────────────────────────
#  Уведомление об обновлении: свой след в чате
# ───────────────────────────────────────────────
# Уведомление «⬇️ Обновился сам…» живёт по особым правилам: оно переживает
# перезапуск бота, поэтому его координаты лежат в settings, а не в памяти,
# и убирает его не гигиена панелей, а этот файл. Подробности — в докстрингах
# ниже и в карте проекта (`references/dependencies-runtime.md`).


def _load_notice() -> tuple[str, list, float]:
    """
    Достаёт из settings след прошлого уведомления:
    («метка сборки», [[чат, id]…], время отправки).

    В базе лежит JSON `{"build": "…", "msgs": [[чат, id], …], "sent_at": …}`.
    Форматов набралось три, и разбираются все — база боевого сервера помнит
    старые:
      • голый список пар (до 2026-08-05) — метки нет, времени нет;
      • {"build", "msgs"} (2026-08-05) — времени нет;
      • {"build", "msgs", "sent_at"} (03.09.2026) — время отправки, unix.

    Времени нет (0.0) означает «когда отправлено — неизвестно». Такой след
    по сроку НЕ убирается: гадать о возрасте сообщения нельзя, а прежняя
    уборка (новое стирает старое, протухшее снимается при запуске) для него
    работает как работала.
    """
    from config import UPDATE_NOTICE_MSGS_KEY
    from database.history import get_setting

    raw = get_setting(UPDATE_NOTICE_MSGS_KEY, "")
    if not raw:
        return "", [], 0.0
    try:
        data = json.loads(raw)
    except (TypeError, ValueError):
        return "", [], 0.0
    if isinstance(data, list):          # старый формат: только список пар
        return "", data, 0.0
    if isinstance(data, dict):
        try:
            sent_at = float(data.get("sent_at") or 0)
        except (TypeError, ValueError):
            sent_at = 0.0
        return str(data.get("build") or ""), list(data.get("msgs") or []), sent_at
    return "", [], 0.0


def _save_notice(build: str, msgs: list, sent_at: float = 0.0) -> None:
    """
    Запоминает след уведомления. Пустой список тоже пишем — это «следа нет».

    sent_at — время отправки (unix). По нему уведомление убирается через
    config.UPDATE_NOTICE_TTL_SEC; ноль означает «время неизвестно, по сроку
    не трогать». При снятии следа время не нужно и остаётся нулём.
    """
    from config import UPDATE_NOTICE_MSGS_KEY
    from database.history import set_setting

    set_setting(UPDATE_NOTICE_MSGS_KEY,
                json.dumps({"build": build, "msgs": msgs, "sent_at": sent_at},
                           ensure_ascii=False))


async def forget_update_notice(application, stale_only: bool = False) -> None:
    """
    Стирает ПРЕДЫДУЩЕЕ сообщение об обновлении (2026-08-04, просьба Максима:
    «пусть удаляет старое своё сообщение об обновлении»). Иначе в личке
    владельца копится лента одинаковых уведомлений — бот обновляется тем чаще,
    чем чаще идут правки.

    Зовут её ДВОЕ, и вторым она появилась 2026-08-05 по разбору «почему
    сообщение про v3.84 так и висит»:
      • сам цикл самообновления, перед отправкой нового уведомления
        (stale_only=False) — «новое стирает старое»;
      • `main.post_init` при КАЖДОМ запуске (stale_only=True) — потому что код
        приезжает на сервер ТРЕМЯ путями, а уведомление шлёт только один.
        Отправка с ПК Максима (`.bat` → deploy-restart.sh) и кнопка
        «🔄 ПЕРЕЗАПУСК» обновляют код молча, ничего не удаляя, — и уведомление
        от прошлого САМОобновления висело в чате до следующего самообновления,
        то есть могло не исчезнуть никогда (например, при выключенном тумблере
        самообновления).

    ⚠️ ЧТО ЗНАЧИТ stale_only. При запуске нельзя стирать всё подряд: сразу
    после самообновления в чате лежит СВЕЖЕЕ «⬇️ Обновился сам…», и бот,
    поднявшись через несколько секунд, снёс бы собственное сообщение — человек
    не успел бы его прочитать, а весь смысл уведомления в том, чтобы он узнал
    о новой версии. Поэтому «протухшим» считается только след, снятый с ДРУГОГО
    кода: сравниваем метку сборки в следе с меткой РАБОТАЮЩЕГО кода
    (`config.BOT_BUILD`, снята при импорте). Совпали — уведомление про этот
    самый код, оставляем. Разошлись — код с тех пор сменился другим путём,
    сообщение устарело, убираем. Метка неизвестна (старый формат записи, нет
    файла `.build`) — не трогаем: лучше лишнее сообщение, чем стёртое нужное.

    Тихая: сообщение мог удалить сам владелец, а старше 48 часов Telegram
    ботам удалять не даёт — оба случая штатные, ругаться на них нечего, но в
    лог они идут предупреждением (2026-08-05: раньше стояла отладочная запись,
    и молчаливо не сработавшая уборка не оставляла в логе ни следа).
    ⚠️ Гигиену панелей (`register_and_clean_bot_message`) здесь применять
    НЕЛЬЗЯ: она стирает ПОСЛЕДНЕЕ сообщение бота в чате, каким бы оно ни
    было, — уведомление об обновлении снесло бы открытую админ-панель.
    Поэтому у него свой, отдельный след.
    """
    from config import BOT_BUILD

    build, msgs, _sent_at = _load_notice()
    if not msgs:
        return
    if stale_only:
        if not build or not BOT_BUILD:
            return                      # не с чем сравнивать — не трогаем
        if build == BOT_BUILD:
            return                      # уведомление про работающий код
        logger.info("⬇️ Убираю уведомление об обновлении от прошлой сборки %s "
                    "(сейчас %s): код приехал другим путём", build, BOT_BUILD)
    for pair in msgs:
        try:
            chat_id, message_id = pair
            await application.bot.delete_message(chat_id=chat_id, message_id=message_id)
        except Exception as e:
            logger.warning("⚠️ Не удалось удалить прошлое уведомление об обновлении %s: %s",
                           pair, e)
    # След снимаем В ЛЮБОМ случае, даже если удалить не вышло: иначе бот будет
    # ломиться в то же сообщение при каждом запуске до скончания века.
    _save_notice(BOT_BUILD, [])


def notice_since(build: str, sent_at: float, current_build: str = "",
                 started_at: float | None = None) -> float:
    """
    ОТ КАКОГО МОМЕНТА считать возраст уведомления. Ноль — считать не от чего,
    трогать нельзя.

    Три случая:
      • время отправки записано — берём его, вопросов нет;
      • времени нет, но метка следа СОВПАДАЕТ с работающим кодом — значит
        уведомление про этот самый код, то есть отправлено при последнем
        обновлении. Точного времени не знаем, но старше запуска бота оно быть
        не может: считаем от запуска;
      • времени нет и метка ЧУЖАЯ (или её нет вовсе) — не трогаем. Уведомление
        от какого-то прошлого кода, возраст неизвестен, и снести его вслепую
        хуже, чем оставить.

    ⚠️ Второй случай появился 03.09.2026 по живому промаху. Сначала правило
    было проще — «времени нет, не трогаем», — и выглядело осторожным. На деле
    оно означало, что ПЕРВОЕ же уведомление после перехода на новый код висит
    вечно: отправлял его ещё старый код, который время писать не умел. То есть
    осторожность давала ровно то, от чего избавлялись.

    Отдельной функцией — чтобы выбор точки отсчёта проверялся без Телеграма,
    базы и часов (selftest::check_update_notice).
    """
    if sent_at and sent_at > 0:
        return float(sent_at)
    if build and current_build and build == current_build:
        return _STARTED_AT if started_at is None else float(started_at)
    return 0.0


def notice_expired(sent_at: float, now: float | None = None) -> bool:
    """
    Пора ли убирать уведомление: прошло ли UPDATE_NOTICE_TTL_SEC с отправки.

    Отдельной функцией — чтобы расчёт можно было проверить без Телеграма и
    без базы (selftest::check_update_notice). Само удаление — в
    drop_expired_notice ниже.

    Ноль (и всё, что меньше) означает «время отправки неизвестно» — старый
    формат следа. Такой след по сроку НЕ убираем: гадать о возрасте
    сообщения нельзя, а прежняя уборка для него работает как работала.
    """
    from config import UPDATE_NOTICE_TTL_SEC

    if not sent_at or sent_at <= 0:
        return False
    if now is None:
        now = time.time()
    return (now - sent_at) >= UPDATE_NOTICE_TTL_SEC


async def drop_expired_notice(application) -> None:
    """
    Убирает уведомление «⬇️ Обновился сам…», если оно провисело дольше
    UPDATE_NOTICE_TTL_SEC (03.09.2026, просьба Максима: «пусть удаляется
    через 10 минут»).

    ⚠️ ПОЧЕМУ НЕ utils.schedule_delete, КАК У ОСТАЛЬНЫХ СЛУЖЕБНЫХ СООБЩЕНИЙ.
    Тот держит отложенное удаление в памяти процесса, а это уведомление
    отправляется ПРЯМО ПЕРЕД перезапуском: задача умерла бы вместе со старым
    процессом, и сообщение осталось бы висеть навсегда. Поэтому время отправки
    лежит в следе (settings), а убирает сообщение уже НОВЫЙ процесс — вот эта
    функция.

    Зовут её двое, и оба нужны:
      • цикл самообновления на каждом шаге (раз в AUTO_UPDATE_TICK_SEC) —
        обычный случай, бот работает и сам за собой прибирает;
      • main.post_init при запуске — если бот простоял выключенным дольше
        десяти минут, уведомление устарело ещё до его пробуждения.

    ⚠️ НЕ ПУТАТЬ с forget_update_notice: та убирает уведомление ПРОШЛОЙ
    сборки (новое стирает старое) и о сроках ничего не знает. Эта убирает
    уведомление про ТЕКУЩИЙ код, просто потому что оно провисело своё. Друг
    другу они не мешают: обе снимают след, и кто сработал первым, тот и снял.

    Тихая: сообщение мог удалить сам владелец, чат мог пропасть, а старше 48
    часов Telegram ботам удалять не даёт — всё это штатные случаи, в лог идут
    предупреждением, но работу не рвут.
    """
    from config import BOT_BUILD

    build, msgs, sent_at = _load_notice()
    # Точку отсчёта выбирает notice_since: записанное время, а если его нет —
    # запуск бота, но только когда след помечен ТЕКУЩИМ кодом (см. её докстринг).
    since = notice_since(build, sent_at, BOT_BUILD)
    if not msgs or not notice_expired(since):
        return

    logger.info("⬇️ Убираю уведомление об обновлении: провисело своё%s",
                "" if sent_at else " (время отправки не записано, считал от запуска)")
    for pair in msgs:
        try:
            chat_id, message_id = pair
            await application.bot.delete_message(chat_id=chat_id, message_id=message_id)
        except Exception as e:
            logger.warning("⚠️ Не удалось убрать уведомление об обновлении %s: %s",
                           pair, e)
    # След снимаем В ЛЮБОМ случае — по той же причине, что и в
    # forget_update_notice: иначе бот будет ломиться в то же сообщение вечно.
    _save_notice(BOT_BUILD, [])


# ───────────────────────────────────────────────
#  Самообновление: бот сам забирает новый код
