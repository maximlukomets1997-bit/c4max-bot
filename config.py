# ─── Метка сборки (2026-07-31) ───────────────────────────────
# Короткий номер коммита, который РЕАЛЬНО лежит на сервере. Пишет его
# deploy.sh в файл `.build` при каждом заходе (см. там же, почему через trap).
#
# Зачем понадобилась. Номер версии поднимает только «Отправить изменения на
# GitHub.bat», то есть отправка с ПК Максима. Правки, приехавшие другим путём
# (из сессии Claude через pull request), номер НЕ меняют — и панель показывала
# прежний, что по задумке читается как «сервер ещё не забрал», хотя забрал.
# Поймано 2026-07-31 на двух обновлениях подряд. Хэш коммита меняется ВСЕГДА,
# кем бы правка ни была сделана, поэтому вопрос «что реально работает на
# сервере» он закрывает надёжнее номера.
#
# Файла нет (дома на Windows, первый запуск на новом сервере, запуск не из
# git-клона) — метка пустая, и всё показывается как раньше. Это не поломка.
#
# ⚠️ ЧИТАТЬ ЧЕРЕЗ ФУНКЦИЮ, А НЕ ЧЕРЕЗ BOT_BUILD, если нужен код НА ДИСКЕ.
# `BOT_BUILD` снят один раз при импорте config — это метка того кода, который
# СЕЙЧАС РАБОТАЕТ В ПАМЯТИ, и после обновления она нарочно остаётся прежней.
# А `read_build_mark()` идёт в файл заново и отдаёт то, что уже лежит на диске.
# Разница между ними и есть «бот скачал новое, но ещё не перезапустился» — на
# ней держится уборка старых уведомлений об обновлении (jobs/update.py).
def read_build_mark() -> str:
    try:
        path = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".build")
        with open(path, encoding="utf-8") as f:
            # В файле «<хэш> <дата> <время>» — берём первое слово.
            return f.read().split()[0][:12]
    except Exception:
        return ""


